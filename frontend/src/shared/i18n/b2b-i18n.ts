export type B2BWord = keyof typeof b2bWords;
export function useB2BText() {
  const { locale } = useLocale();
  const i = locale.startsWith("de")
    ? 1
    : locale.startsWith("fr")
      ? 2
      : locale.startsWith("es")
        ? 3
        : 0;
  return (key: B2BWord) => b2bWords[key][i];
}
